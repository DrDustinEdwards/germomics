// One-off: store all 10 raw WebVTT transcripts verbatim on posts.transcript, matched to each
// episode by the 3-digit code in the filename. Full fidelity — ms timing + end times kept; no
// flattening. SQL generated via Drizzle, applied with `wrangler d1 execute --remote --file`.
//
// Run:  node scripts/import-transcripts.ts   (writes scripts/_generated/transcripts.sql)
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { drizzle } from "drizzle-orm/sqlite-proxy";
import { eq, sql } from "drizzle-orm";
import { posts } from "../app/db/schema.ts";

const here = dirname(fileURLToPath(import.meta.url));
const db = drizzle(async () => ({ rows: [] }));

const TRANSCRIPT_DIR = join(
  process.env.USERPROFILE || process.env.HOME || "",
  "Downloads",
  "transcripts",
);

// 3-digit episode code -> the immutable feed guid.
const NUM_TO_GUID: Record<string, string> = {
  "001": "https://germomics.com/?p=163",
  "002": "https://germomics.com/?p=219",
  "003": "https://germomics.com/?p=311",
  "004": "https://germomics.com/?p=428",
  "005": "https://germomics.com/?p=461",
  "006": "https://germomics.com/?p=493",
  "007": "https://germomics.com/?p=513",
  "008": "https://germomics.com/?p=530",
  "009": "https://germomics.com/?p=560",
  "010": "https://germomics.com/?p=563",
};

function lit(v: unknown): string {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "NULL";
  if (typeof v === "boolean") return v ? "1" : "0";
  return `'${String(v).replace(/'/g, "''")}'`;
}

const files = readdirSync(TRANSCRIPT_DIR).filter((f) => f.toLowerCase().endsWith(".vtt"));
const byNum: Record<string, string> = {};
for (const f of files) {
  const m = f.match(/(\d{3})/);
  if (!m) throw new Error(`no 3-digit code in filename: ${f}`);
  byNum[m[1]] = f;
}

const statements: string[] = [];
for (const num of Object.keys(NUM_TO_GUID).sort()) {
  const file = byNum[num];
  if (!file) throw new Error(`missing VTT for episode ${num}`);
  const vtt = readFileSync(join(TRANSCRIPT_DIR, file), "utf8");
  if (!/^﻿?WEBVTT/.test(vtt)) throw new Error(`${file} does not start with WEBVTT`);

  const q = db
    .update(posts)
    .set({ transcript: vtt, updatedAt: sql`(datetime('now'))` })
    .where(eq(posts.guid, NUM_TO_GUID[num]));

  const { sql: text, params } = q.toSQL();
  let i = 0;
  const inlined = text.replace(/\?/g, () => lit(params[i++]));
  if (i !== params.length) throw new Error(`param count mismatch for ${num}`);
  statements.push(`-- ${num} ${file} (${vtt.length} chars)\n${inlined};`);
}

const out =
  "-- GENERATED by scripts/import-transcripts.ts — do not edit by hand.\n" +
  "-- Stores all 10 raw WebVTT transcripts verbatim, matched by 3-digit code.\n" +
  statements.join("\n") +
  "\n";

const outPath = join(here, "_generated", "transcripts.sql");
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out, "utf8");
console.log(`Wrote ${statements.length} UPDATE statements to ${outPath} (${out.length} bytes)`);
