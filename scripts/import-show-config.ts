// One-off: populate the single show_config row from the legacy feed's channel tags.
// Idempotent upsert on id = 1 (getShowConfig reads the first row). Drizzle-generated SQL,
// applied with `wrangler d1 execute --remote --file`.
//
// NOTE: the schema exposes a single `apple_category` column and rss.server emits one
// <itunes:category>. The legacy feed declared three (Science › Life Sciences;
// Society & Culture › Documentary; Education › Courses). We store the primary "Science";
// full multi-category fidelity needs a small schema + feed enhancement (flagged as follow-up).
// The channel <link> is not a column — the feed derives it from the request origin.
//
// Run:  node scripts/import-show-config.ts   (writes scripts/_generated/show-config.sql)
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { drizzle } from "drizzle-orm/sqlite-proxy";
import { showConfig } from "../app/db/schema.ts";

const here = dirname(fileURLToPath(import.meta.url));
const db = drizzle(async () => ({ rows: [] }));

function lit(v: unknown): string {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "NULL";
  if (typeof v === "boolean") return v ? "1" : "0";
  return `'${String(v).replace(/'/g, "''")}'`;
}

const row = {
  id: 1,
  title: "Germomics",
  description:
    "A mix of microbiology and history, this series connects different aspects of modern life and society to microbes, bacteria, viruses, and parasites through seemingly unconnected natural events, scientific discoveries, and human inventions.",
  author: "Dr. Dustin Edwards",
  ownerEmail: "germomics@gmail.com",
  artwork: "https://germomics.com/wp-content/uploads/2022/06/germomics-logo-square-artwork.jpg",
  appleCategory: "Science",
  language: "en-US",
  itunesType: "serial" as const,
  explicit: false,
};

const q = db
  .insert(showConfig)
  .values(row)
  .onConflictDoUpdate({
    target: showConfig.id,
    set: {
      title: row.title,
      description: row.description,
      author: row.author,
      ownerEmail: row.ownerEmail,
      artwork: row.artwork,
      appleCategory: row.appleCategory,
      language: row.language,
      itunesType: row.itunesType,
      explicit: row.explicit,
    },
  });

const { sql: text, params } = q.toSQL();
let i = 0;
const inlined = text.replace(/\?/g, () => lit(params[i++]));
if (i !== params.length) throw new Error("param count mismatch");

const out =
  "-- GENERATED by scripts/import-show-config.ts — do not edit by hand.\n" +
  inlined +
  ";\n";

const outPath = join(here, "_generated", "show-config.sql");
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, out, "utf8");
console.log(out);
console.log(`Wrote show_config upsert to ${outPath}`);
