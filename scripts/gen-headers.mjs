// Writes public/_headers, the headers Cloudflare's asset server puts on the static files (which never run the
// Worker), from the set the Worker applies (app/lib/header-set.ts). `npm run build` runs it first, so a deploy always
// carries the current set; the file is committed too, for the family check to read.
import { writeFileSync } from "node:fs";
import { headersFile } from "@dustinedwards/site-runtime/headers";
import { SECURITY_HEADERS } from "../app/lib/header-set.ts";

// A year for Vite's content-hashed build output, whose URL changes with its bytes. The fonts sit at stable names that
// scripts/fetch-fonts.mjs rewrites in place, so a day, then revalidated by the asset server's ETag: a replaced font
// reaches every reader. Other files at stable paths keep the default revalidation.
const IMMUTABLE = { "Cache-Control": "public, max-age=31536000, immutable" };
const A_DAY = { "Cache-Control": "public, max-age=86400" };

writeFileSync(
  new URL("../public/_headers", import.meta.url),
  headersFile(SECURITY_HEADERS, {
    comment: "GENERATED by scripts/gen-headers.mjs from app/lib/header-set.ts. Do not edit.",
    // charset=utf-8 on text, and cross-origin CORP on stylesheets, scripts, SVG and fonts, which Carrel's preview
    // (a sandboxed frame with an opaque origin) loads.
    charset: true,
    paths: { "/assets/*": IMMUTABLE, "/fonts/*": A_DAY },
  }),
);
