// Writes public/_headers, the headers Cloudflare's asset server puts on the static files (which never run the
// Worker), from the set the Worker applies (app/lib/header-set.ts). `npm run build` runs it first; the file is not
// committed.
import { writeFileSync } from "node:fs";
import { headersFile } from "@dustinedwards/site-runtime/headers";
import { CROSS_ORIGIN, SECURITY_HEADERS } from "../app/lib/header-set.ts";

// A year for files whose URL changes with their bytes: Vite's content-hashed build output, and the fonts
// (scripts/fetch-fonts.mjs writes new files rather than new bytes). Files at stable paths keep the default revalidation.
const IMMUTABLE = { "Cache-Control": "public, max-age=31536000, immutable" };

writeFileSync(
  new URL("../public/_headers", import.meta.url),
  headersFile({ ...SECURITY_HEADERS, ...CROSS_ORIGIN }, {
    comment: "GENERATED by scripts/gen-headers.mjs from app/lib/header-set.ts. Do not edit.",
    paths: { "/assets/*": IMMUTABLE, "/fonts/*": IMMUTABLE },
  }),
);
